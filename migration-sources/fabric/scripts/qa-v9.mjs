check('Spark workbench teaches when not to use Spark',spark.includes('not by default')&&spark.includes('Prefer SQL/dbt'));
check('Power BI remains deferred',shell.includes('Power BI · next pass'));
const failed=checks.filter(c=>!c.ok); for(const c of checks) console.log(`${c.ok?'PASS':'FAIL'}  ${c.name}`);
console.log(`\n${checks.length-failed.length}/${checks.length} V9 static/depth QA checks passed.`); if(failed.length) process.exit(1);
