const read=(file)=>fs.readFileSync(file,'utf8');
const checks=[]; const check=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const types=read('src/types/app.ts');
const app=read('src/App.tsx');
const shell=read('src/components/AppShell.tsx');
const hub=read('src/components/FabricHub.tsx');
const curriculum=read('src/data/curriculum.ts');
const airflow=read('src/components/AirflowStudio.tsx');
const airflowRuntime=read('src/lib/airflowRuntime.ts');
const choice=read('src/components/ToolChoiceStudio.tsx');
const dbt=read('src/components/DbtStudio.tsx');
const properties=read('src/components/PropertiesPanel.tsx');
const pipeline=read('src/lib/pipeline.ts');
const dataRuntime=read('src/lib/dataRuntime.ts');
const spark=read('src/components/FabricRuntimeStudio.tsx');
check('Airflow and tool-choice routes exist',types.includes("| 'airflow'")&&types.includes("| 'toolchoice'"));
check('App routes Airflow workbench',app.includes("case 'airflow'")&&app.includes('<AirflowStudio'));
check('App routes engineering decision lab',app.includes("case 'toolchoice'")&&app.includes('<ToolChoiceStudio'));
check('Fabric navigation exposes Airflow',shell.includes("label: 'Apache Airflow Job'"));
check('Fabric navigation exposes decision lab',shell.includes("label: 'Engineering decision lab'"));
check('Fabric curriculum includes Airflow module',curriculum.includes("id: 'fabric-airflow'")&&curriculum.includes('FabricRunItemOperator'));
check('Fabric curriculum includes tool-choice module',curriculum.includes("id: 'fabric-tool-choice'"));
check('Fabric curriculum includes dbt module',curriculum.includes("id: 'fabric-dbt'"));
check('Hub maps Airflow module to workbench',hub.includes("'fabric-airflow': 'airflow'"));
check('Hub uses dynamic module count',hub.includes('{fabricModules.length} learning workbenches'));
check('Decision lab compares transformation and orchestration tools',choice.includes('SQL, dbt, Python, Spark, Pipeline or Airflow')&&choice.includes('Do not use distributed compute'));
check('Decision lab includes explicit no-Spark reasoning',choice.includes('Starting Spark only because')&&choice.includes('One-off aggregation'));
check('Airflow workbench has graph and Python code',airflow.includes('DAG graph')&&airflow.includes('DAG Python'));
check('Airflow workbench can apply code back to graph',airflow.includes('parseAirflowDagCode')&&airflow.includes('Apply code → graph'));
